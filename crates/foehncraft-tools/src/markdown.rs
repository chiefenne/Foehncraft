//! The catalogue as Markdown (`docs/tools.md`, `foehn commands --markdown`).

use crate::registry;
use serde_json::Value;

/// The type of a property of a JSON Schema, short.
fn type_of(p: &Value, defs: &Value) -> String {
    if let Some(r) = p.get("$ref").and_then(Value::as_str) {
        let name = r.rsplit('/').next().unwrap_or(r);
        return match defs.get(name) {
            Some(d) => type_of(d, defs),
            None => name.to_string(),
        };
    }
    if let Some(e) = p.get("enum").and_then(Value::as_array) {
        return e
            .iter()
            .map(|v| v.as_str().map_or(v.to_string(), |s| format!("`{s}`")))
            .collect::<Vec<_>>()
            .join(" \\| ");
    }
    let t = match p.get("type") {
        Some(Value::String(s)) => s.clone(),
        Some(Value::Array(a)) => a
            .iter()
            .filter_map(Value::as_str)
            .filter(|s| *s != "null")
            .collect::<Vec<_>>()
            .join(" or "),
        _ => {
            if let Some(any) = p.get("anyOf").and_then(Value::as_array) {
                return any
                    .iter()
                    .filter(|v| v.get("type").and_then(Value::as_str) != Some("null"))
                    .map(|v| type_of(v, defs))
                    .collect::<Vec<_>>()
                    .join(" or ");
            }
            return "any".into();
        }
    };
    if t == "array" {
        if let Some(i) = p.get("items") {
            return format!("array of {}", type_of(i, defs));
        }
        if let Some(Value::Array(pi)) = p.get("prefixItems") {
            return format!("array of {} {}", pi.len(), type_of(&pi[0], defs));
        }
    }
    t
}

fn one_line(s: &str) -> String {
    s.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace("[`", "`")
        .replace("`]", "`")
        .replace('|', "\\|")
}

/// The rows of the fields of an object schema.
fn fields(schema: &Value, with_default: bool) -> String {
    let defs = schema.get("$defs").cloned().unwrap_or(Value::Null);
    let Some(props) = schema.get("properties").and_then(Value::as_object) else {
        return "No fields.\n".into();
    };
    if props.is_empty() {
        return "No fields.\n".into();
    }
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|a| a.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let mut s = if with_default {
        String::from("| Field | Type | Default | Description |\n|---|---|---|---|\n")
    } else {
        String::from("| Field | Type | Description |\n|---|---|---|\n")
    };
    for (name, p) in props {
        let desc = one_line(p.get("description").and_then(Value::as_str).unwrap_or(""));
        let ty = type_of(p, &defs);
        if with_default {
            let def = if required.contains(&name.as_str()) {
                "required".to_string()
            } else {
                match p.get("default") {
                    Some(Value::Null) | None => "–".into(),
                    Some(v) => format!("`{v}`"),
                }
            };
            s.push_str(&format!("| `{name}` | {ty} | {def} | {desc} |\n"));
        } else {
            s.push_str(&format!("| `{name}` | {ty} | {desc} |\n"));
        }
    }
    s
}

/// `docs/tools.md`.
pub fn catalogue() -> String {
    let reg = registry();
    let mut s = String::from(
        "# Tools\n\n\
         Generated by `foehn commands --markdown` from the tool registry (D196, crate \
         `foehncraft-tools`); do not edit by hand. Every function of the engine is a tool \
         with a stable id, a contract version, typed input and output and an action kind \
         (D198): `read` reads and computes, `write-files` writes files, `start-run` starts a \
         run. The command line, the Python package and the MCP server reach the same tools. \
         `foehn commands` prints this catalogue as JSON (`foehn.tool-catalogue`) with the \
         full input and output schemas; `foehn call <id> --input file.json` runs a tool and \
         prints the result envelope (`foehn.tool-result`, see \
         [interfaces.md](interfaces.md#tool-registry-d196)).\n\n\
         | Id | Version | Action | Summary |\n|---|---|---|---|\n",
    );
    for e in &reg {
        s.push_str(&format!(
            "| [`{}`](#{}) | {} | {} | {} |\n",
            e.spec.id,
            e.spec.id.replace('.', ""),
            e.spec.version,
            e.spec.action.name(),
            one_line(e.spec.summary)
        ));
    }
    for e in &reg {
        s.push_str(&format!(
            "\n## `{}`\n\n{}\n\nCategory `{}`, action `{}`, version {}{}.\n\n### Input\n\n{}",
            e.spec.id,
            e.spec.summary,
            e.spec.category.name(),
            e.spec.action.name(),
            e.spec.version,
            if e.spec.streams {
                ", streams the rows of the run record"
            } else {
                ""
            },
            fields(&e.input_schema(), true),
        ));
        let out = e.output_schema();
        if out.get("properties").is_some() {
            s.push_str(&format!("\n### Output\n\n{}", fields(&out, false)));
        } else {
            s.push_str("\n### Output\n\nA JSON object (see the description above).\n");
        }
    }
    s
}
