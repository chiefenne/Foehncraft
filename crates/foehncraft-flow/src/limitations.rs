use std::sync::OnceLock;

/// The grades of the features (generated by
/// `tools/release/verification_status.py`).
const GRADES: &str = include_str!("../../../docs/verification/grades.json");

/// GPUs on which the GPU checks ran (D199 Q5); a run on another GPU gets
/// LIM005 until a run of the GPU checks there adds it.
pub const VERIFIED_DEVICES: &[&str] = &["Tesla T4"];

/// One limitation of a run.
#[derive(Debug, Clone, PartialEq, Serialize, schemars::JsonSchema)]
pub struct Limitation {
    /// `LIM001` … `LIM006` (the D78 registry).
    pub code: &'static str,
    /// The feature of `docs/verification/features.toml` it concerns.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub feature: Option<String>,
    /// What it means for the result.
    pub message: String,
}

impl Limitation {
    fn new(code: &'static str, feature: Option<&str>, message: String) -> Self {
        Self {
            code,
            feature: feature.map(str::to_string),
            message,
        }
    }
}

/// A feature of the status page.
#[derive(Debug, Clone)]
pub struct Grade {
    /// Feature id.
    pub id: String,
    /// What the user sees.
    pub title: String,
    /// `verified`, `partial` or `unverified`.
    pub grade: String,
    /// Why the grade is not higher.
    pub why: Vec<String>,
    /// The known gaps.
    pub gaps: Vec<String>,
    /// Validated range: (key, lower, upper).
    pub range: Vec<(String, f64, f64)>,
}

/// The grades compiled into the binary.
pub fn grades() -> &'static [Grade] {
    static G: OnceLock<Vec<Grade>> = OnceLock::new();
    G.get_or_init(|| {
        let v: serde_json::Value = serde_json::from_str(GRADES).unwrap_or_default();
        let list = v
            .get("features")
            .and_then(|f| f.as_array())
            .cloned()
            .unwrap_or_default();
        list.iter()
            .map(|f| {
                let s = |k: &str| {
                    f.get(k)
                        .and_then(|x| x.as_str())
                        .unwrap_or_default()
                        .to_string()
                };
                let list = |k: &str| -> Vec<String> {
                    f.get(k)
                        .and_then(|g| g.as_array())
                        .map(|g| {
                            g.iter()
                                .filter_map(|x| x.as_str().map(str::to_string))
                                .collect()
                        })
                        .unwrap_or_default()
                };
                let (why, gaps) = (list("why"), list("gaps"));
                let range = f
                    .get("range")
                    .and_then(|r| r.as_object())
                    .map(|r| {
                        r.iter()
                            .filter_map(|(k, b)| {
                                let lo = b.get(0)?.as_f64()?;
                                let hi = b.get(1)?.as_f64()?;
                                Some((k.clone(), lo, hi))
                            })
                            .collect()
                    })
                    .unwrap_or_default();
                Grade {
                    id: s("id"),
                    title: s("title"),
                    grade: s("grade"),
                    why,
                    gaps,
                    range,
                }
            })
            .collect()
    })
}

/// The grade of a feature id.
pub fn grade(id: &str) -> Option<&'static Grade> {
    grades().iter().find(|g| g.id == id)
}

/// The features of the status page that a case switches on (ids of
/// `docs/verification/features.toml`). Only switches a user sets are
/// listed; the numerics every run uses are not.
pub fn features_in_use(case: &FlowCase) -> Vec<&'static str> {
    let mut f: Vec<&'static str> = Vec::new();
    // the mesh
    let format = case.mesh.format.clone().or_else(|| {
        let p = case.mesh.file.as_ref()?;
        let ext = p
            .extension()
            .and_then(|e| e.to_str())
            .unwrap_or("")
            .to_ascii_lowercase();
        Some(
            match ext.as_str() {
                "su2" => "su2",
                "cgns" => "cgns",
                "vtk" | "vtu" => "vtk",
                "msh" => "msh",
                _ => "openfoam",
            }
            .to_string(),
        )
    });
    match format.as_deref() {
        Some("gmsh" | "msh") => f.push("mesh.gmsh"),
        Some("su2") => f.push("mesh.su2"),
        Some("cgns") => f.push("mesh.cgns"),
        Some("vtk") => f.push("mesh.vtk"),
        Some("industry_msh") => f.push("mesh.industry-msh"),
        Some("openfoam") => f.push("mesh.openfoam"),
        _ => {}
    }
    // pressure-velocity coupling and time
    match &case.time {
        Some(t) => {
            f.push("coupling.piso");
            f.push(match t.scheme {
                TimeScheme::Bdf1 => "time.bdf1",
                TimeScheme::Bdf2 => "time.bdf2",
                TimeScheme::CrankNicolson => "time.crank-nicolson",
            });
        }
        None => f.push(if case.solver.algorithm == Some(Algorithm::Coupled) {
            "coupling.coupled"
        } else {
            "coupling.simplec"
        }),
    }
    // boundary conditions
    let mut rough = false;
    for bc in case.boundary.values() {
        let id = match bc.type_name() {
            "wall" => "bc.wall",
            "velocity-inlet" => "bc.velocity-inlet",
            "mass-flow-inlet" => "bc.mass-flow-inlet",
            "static-pressure-inlet" => "bc.static-pressure-inlet",
            "total-pressure-inlet" => "bc.total-pressure-inlet",
            "static-pressure-outlet" => "bc.static-pressure-outlet",
            "total-pressure-outlet" => "bc.total-pressure-outlet",
            "convective-outlet" => "bc.convective-outlet",
            "slip-wall" => "bc.slip-wall",
            "symmetry" => "bc.symmetry",
            "wedge" => "bc.wedge",
            "periodic" => "bc.periodic",
            _ => continue,
        };
        f.push(id);
        rough |= bc.roughness() > 0.0;
    }
    // turbulence
    let t = &case.turbulence;
    if !t.is_laminar() {
        f.push(match t.model {
            TurbulenceModel::KOmegaSst => "turbulence.sst",
            TurbulenceModel::KEpsilon => "turbulence.k-epsilon",
            TurbulenceModel::RealizableKEpsilon => "turbulence.realizable-k-epsilon",
            TurbulenceModel::KEpsilonZetaF => "turbulence.zeta-f",
            TurbulenceModel::KEpsilonZetaF0 => "turbulence.zeta-f0",
            _ => "turbulence.elliptic-blending",
        });
        f.push(match t.treatment() {
            WallTreatment::Automatic => "wall.automatic",
            WallTreatment::LowRe => "wall.low-re",
            WallTreatment::Scalable => "wall.scalable",
            WallTreatment::Standard => "wall.standard",
            WallTreatment::Compound => "wall.compound",
            WallTreatment::Compound2023 => "wall.compound-2023",
        });
        if t.curvature_correction {
            f.push("turbulence.curvature-correction");
        }
        if t.qcr != QcrMode::None {
            f.push("turbulence.qcr");
        }
        if t.smooth_limits {
            f.push("turbulence.smooth-limits");
        }
        if rough {
            f.push("wall.roughness");
        }
    }
    // heat and scalars
    if !case.scalars.is_empty() {
        f.push("scalar.passive");
        if !t.is_laminar() {
            f.push("scalar.turbulent-prandtl");
            f.push("scalar.thermal-wall-function");
        }
    }
    if case.energy.is_some() {
        f.push("energy.fluid");
        if !t.is_laminar() {
            f.push("energy.turbulent");
        }
    }
    let solid = case
        .regions
        .values()
        .any(|r| r.kind == crate::materials::RegionKind::Solid);
    if solid {
        f.push(if case.time.is_some() {
            "cht.transient"
        } else {
            "cht.steady"
        });
        if !t.is_laminar() {
            f.push("cht.turbulent");
        }
        if case
            .energy
            .as_ref()
            .is_some_and(|e| e.acceleration.is_some())
        {
            f.push("cht.thermal-acceleration");
        }
        if case.energy.as_ref().is_some_and(|e| e.cycle.is_some()) {
            f.push("cht.cycle-coupling");
        }
    }
    if case
        .interfaces
        .values()
        .any(|i| i.contact_resistance.is_some() || i.thin_wall.is_some())
    {
        f.push("cht.contact-thin-wall");
    }
    // rotating machinery
    if !case.mrf.is_empty() {
        f.push(if case.time.is_some() {
            "rotating.mrf-transient"
        } else {
            "rotating.mrf"
        });
    }
    for s in &case.sliding {
        f.push(if s.rotor_interface.is_some() {
            "rotating.sliding-imprint"
        } else {
            "rotating.sliding-conformal"
        });
    }
    if case.mrf.len() + case.sliding.len() > 1 {
        f.push("rotating.several-rotors");
    }
    if !case.schedule.is_empty() {
        f.push("case.schedule");
    }
    if case.run.backend == "cuda" {
        f.push("backend.cuda");
    }
    let mut seen = std::collections::BTreeSet::new();
    f.retain(|id| seen.insert(*id));
    f
}

fn fmt(x: f64) -> String {
    if x != 0.0 && (x.abs() >= 1e4 || x.abs() < 1e-2) {
        format!("{x:.3e}")
    } else {
        format!("{x:.4}")
            .trim_end_matches('0')
            .trim_end_matches('.')
            .to_string()
    }
}

/// The values of the run that a validated range can be compared with:
/// (key, smallest, largest, where).
fn measured(case: &FlowCase, rep: &FlowReport) -> Vec<(&'static str, f64, f64, String)> {
    let mut out = Vec::new();
    let Some(last) = rep.solves.last() else {
        return out;
    };
    if let Some(t) = &last.turbulence {
        // the mean first-cell y⁺ of every wall with a flow along it
        let means: Vec<(f64, &str)> = t
            .walls
            .iter()
            .filter(|w| w.mean.is_finite() && w.max > 0.0)
            .map(|w| (w.mean, w.boundary.as_str()))
            .collect();
        if let (Some(lo), Some(hi)) = (
            means.iter().min_by(|a, b| a.0.total_cmp(&b.0)),
            means.iter().max_by(|a, b| a.0.total_cmp(&b.0)),
        ) {
            let walls = if lo.1 == hi.1 {
                format!("`{}`", lo.1)
            } else {
                format!("`{}` to `{}`", lo.1, hi.1)
            };
            out.push((
                "y_plus_first",
                lo.0,
                hi.0,
                format!("mean first-cell y⁺ of the walls ({walls})"),
            ));
        }
    }
    if let Some(re) = rep.reynolds {
        out.push(("reynolds", re, re, "Reynolds number of the case".into()));
    }
    if let Some(tr) = &last.transient {
        out.push((
            "courant",
            tr.cfl_max,
            tr.cfl_max,
            "largest Courant number".into(),
        ));
    }
    if let Some(r) = &last.remediation {
        out.push((
            "skewness",
            r.max_skewness,
            r.max_skewness,
            "largest face skewness".into(),
        ));
    }
    let num = |s: &Option<crate::expr::Scalar>| s.as_ref().and_then(crate::expr::Scalar::number);
    let (rho, mu) = (num(&case.fluid.density), num(&case.fluid.viscosity));
    let cp = num(&case.fluid.specific_heat);
    let k = num(&case.fluid.conductivity);
    if let (true, Some(mu), Some(cp), Some(k)) = (case.energy.is_some(), mu, cp, k)
        && k > 0.0
    {
        let pr = mu * cp / k;
        out.push(("prandtl", pr, pr, "Prandtl number of the fluid".into()));
    }
    if let (Some(rho), Some(mu)) = (rho, mu) {
        for (name, s) in &case.scalars {
            if let Some(g) = s.diffusivity.number()
                && g > 0.0
                && rho > 0.0
            {
                let pr = mu / (rho * g);
                let what = format!("Prandtl or Schmidt number of `{name}`");
                out.push(("prandtl", pr, pr, what));
            }
        }
    }
    out
}

/// The limitations of a finished run.
pub fn of_run(case: &FlowCase, rep: &FlowReport) -> Vec<Limitation> {
    let mut out = Vec::new();
    let used = features_in_use(case);
    // LIM001: grades
    for id in &used {
        let Some(g) = grade(id) else { continue };
        if g.grade == "verified" {
            continue;
        }
        let why = g
            .gaps
            .first()
            .or(g.why.first())
            .map_or(String::new(), |x| format!(": {x}"));
        out.push(Limitation::new(
            diag::LIM_GRADE,
            Some(id),
            format!(
                "{} is graded {}{why} (docs/verification/status.md)",
                g.title, g.grade
            ),
        ));
    }
    // LIM002: validated ranges
    let values = measured(case, rep);
    let mut reported = Vec::new();
    for id in &used {
        let Some(g) = grade(id) else { continue };
        for (key, lo, hi) in &g.range {
            for (k, a, b, what) in &values {
                if k != key || (*a >= *lo && *b <= *hi) || reported.contains(&(key, lo, hi, what)) {
                    continue;
                }
                reported.push((key, lo, hi, what));
                let value = if (a - b).abs() <= 1e-9 * a.abs().max(1.0) {
                    fmt(*a)
                } else {
                    format!("{} to {}", fmt(*a), fmt(*b))
                };
                out.push(Limitation::new(
                    diag::LIM_RANGE,
                    Some(id),
                    format!(
                        "{what} {value} is outside the validated range {} to {} of {}",
                        fmt(*lo),
                        fmt(*hi),
                        g.title
                    ),
                ));
            }
        }
    }
    // LIM003: steady solves that did not settle
    let open: Vec<&crate::case::Solve> = rep
        .solves
        .iter()
        .filter(|s| s.transient.is_none() && !s.converged)
        .collect();
    let reported_failed = rep.failures.iter().any(|f| f.contains("not converged"));
    if !open.is_empty() && rep.stop.is_none() && !reported_failed {
        let meshes: Vec<String> = open
            .iter()
            .map(|s| {
                format!(
                    "the mesh of {} cells ({} iterations)",
                    s.cells, s.iterations
                )
            })
            .collect();
        out.push(Limitation::new(
            diag::LIM_NOT_SETTLED,
            None,
            format!(
                "steady solve not converged to its tolerance on {}: the result may still change with more iterations",
                meshes.join(", ")
            ),
        ));
    }
    // LIM004: one mesh
    let meshes: std::collections::BTreeSet<&str> =
        rep.solves.iter().map(|s| s.mesh_hash.as_str()).collect();
    if meshes.len() == 1 {
        out.push(Limitation::new(
            diag::LIM_ONE_MESH,
            None,
            "one mesh only: the discretisation uncertainty is not estimated (a level sweep with `[verification] levels` gives the GCI)".into(),
        ));
    }
    // LIM005: the device
    let gpus: std::collections::BTreeSet<&str> = rep
        .solves
        .iter()
        .map(|s| s.device.as_str())
        .filter(|d| !d.starts_with("CPU") && !d.starts_with("cpu") && !d.is_empty())
        .collect();
    for d in gpus {
        if !VERIFIED_DEVICES.iter().any(|v| d.contains(v)) {
            out.push(Limitation::new(
                diag::LIM_DEVICE,
                Some("backend.cuda"),
                format!(
                    "the GPU backend is not verified on `{d}` (verified: {}); run the GPU checks there to add it",
                    VERIFIED_DEVICES.join(", ")
                ),
            ));
        }
    }
    // LIM007: a thermal acceleration (D213): the history before
    // `physical_from` is not physical
    if let Some(a) = rep
        .solves
        .iter()
        .filter_map(|s| s.transient.as_ref())
        .find_map(|t| t.acceleration.as_ref())
    {
        let msg = match a.physical_from {
            Some(t) => format!(
                "thermal acceleration of the solids: the history before t = {} s is not physical \
                 (time series, swings and cycle averages count from there)",
                fmt(t)
            ),
            None => "thermal acceleration of the solids: the run ended before the true ρ c_p was \
                     restored; its history and its end state are those of the accelerated solids"
                .to_string(),
        };
        out.push(Limitation::new(
            diag::LIM_ACCELERATED,
            Some("cht.thermal-acceleration"),
            msg,
        ));
    }
    // LIM008: a cycle-averaged coupling (D204): the solids carry the
    // cycle-mean state
    if let Some(c) = rep
        .solves
        .iter()
        .filter_map(|s| s.transient.as_ref())
        .find_map(|t| t.cycle_coupling.as_ref())
    {
        out.push(Limitation::new(
            diag::LIM_CYCLE,
            Some("cht.cycle-coupling"),
            format!(
                "cycle-averaged coupling of the solids ({} after {} updates): their temperatures are \
                 the steady state of the cycle-mean heat transfer, the swing of the wall \
                 temperature over a cycle is not in the result",
                if c.converged { "converged" } else { "not converged" },
                c.updates.len()
            ),
        ));
    }
    // LIM006: remediation
    if let Some(r) = rep
        .solves
        .iter()
        .filter_map(|s| s.remediation.as_ref())
        .find(|r| !r.changes.is_empty())
    {
        out.push(Limitation::new(
            diag::LIM_REMEDIATION,
            Some("mesh.quality-remediation"),
            format!(
                "automatic mesh remediation active ({} skewed faces, {} poor cells): {}; the scheme is first order on those faces",
                r.skewed_faces,
                r.poor_cells,
                r.changes.join(", ")
            ),
        ));
    }
    out
}

/// The limitations as a Markdown block (`flow.md`).
pub fn markdown(list: &[Limitation]) -> String {
    if list.is_empty() {
        return String::new();
    }
    let mut s = format!(
        "## Limitations ({})\n\nRead these before using the result (D199, [verification status](https://github.com/chiefenne/Foehncraft/blob/main/docs/verification/status.md)):\n\n",
        list.len()
    );
    for l in list {
        s.push_str(&format!("- **{}** {}\n", l.code, l.message));
    }
    s.push('\n');
    s
}

