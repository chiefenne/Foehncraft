//! Limitations of a run (D199): what the user must know before trusting a
//! finished result, in every result summary (`result.json`, the D196 tool
//! envelope, the Python result), at the top of `flow.md` and in the last
//! frame of the log.
//!
//! The limitations are known at the end of a run and add no physics:
//!
//! | Code | Limitation | Taken from |
//! |---|---|---|
//! | LIM001 | a feature in use is graded partial or unverified | the case against the grades of `docs/verification/grades.json` (compiled in) |
//! | LIM002 | a feature in use ran outside its validated range | the `range` of the feature against the result (first-cell y⁺, Reynolds, Prandtl and Courant numbers, skewness) |
//! | LIM003 | a steady solve did not settle | a steady solve that stopped before its tolerance (iteration limit) |
//! | LIM004 | one mesh only | no level sweep: no discretisation uncertainty |
//! | LIM005 | a backend not verified on this device | a GPU that is not in [`VERIFIED_DEVICES`] |
//! | LIM006 | automatic mesh remediation active | the remediation of D50 changed the schemes |
//! | LIM007 | thermal acceleration of the solids (D213) | the history before `physical_from` is not physical |
//! | LIM008 | cycle-averaged coupling (D204) | the solids carry the cycle-mean state, no swing over a cycle |
//!
//! The list never changes a result or the exit code (D199 Q1, Q2): a run
//! with limitations keeps `"status": "finished"` and exit code 0, and the
//! human text says "finished with N limitations".

use crate::case::{FlowCase, FlowReport};
use crate::diag;
